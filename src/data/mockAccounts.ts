for (let i = 11; i <= 126; i++) {
  const padIndex = i < 10 ? `0${i}` : `${i}`;
  const depts = ['销售部', '市场部', '技术部', '财务部', '客服中心', '运营部', '供应链'];
  const dept = depts[i % depts.length];
  const protos: ('IMAP' | 'POP3' | 'Exchange')[] = ['IMAP', 'POP3', 'Exchange'];
  const proto = protos[i % protos.length];
  const hosts = ['outlook.office365.com', 'imap.exmail.qq.com:993', 'pop3.qiye.163.com:995', 'mail.corp.net:993'];
  const host = hosts[i % hosts.length];

  const fn = sampleFirstNames[i % sampleFirstNames.length];
  const ln = sampleLastNames[(i * 3) % sampleLastNames.length];
  const code = Math.floor(1000 + (i * 731) % 9000);
  const suffix = (i % 2 === 0 ? 'outlook.com' : 'hotmail.com');
  const email = `${fn}${ln}${code}@${suffix}`;

  const secondOffset = (126 - i) * 2;
  const timeSec = Math.max(0, 22 - (i % 30));
  const createdStr = `2026-08-01 13:32:${timeSec.toString().padStart(2, '0')}`;

  INITIAL_MAIL_ACCOUNTS.push({
    id: `acc-${padIndex}`,
    accountName: email,
    emailAddress: email,
    clientId: `cli_${(i * 987123).toString(16).slice(0, 11)}`,
    usageStatus: i % 5 === 0 ? '已用' : '未用',
    createdTime: createdStr,
    refreshResult: i % 11 === 0 ? '刷新失败' : i % 3 === 0 ? '刷新成功' : '未刷新',
    protocol: proto,
    serverHost: host,
    status: i % 7 === 0 ? 'syncing' : i % 13 === 0 ? 'error' : 'active',
    unreadCount: (i * 3) % 18,
    totalMails: 100 + i * 42,
    lastSyncTime: `10:${(60 - (i % 60)).toString().padStart(2, '0')}:15`,
    tags: [`${dept}`, `编号${padIndex}`],
    department: dept,
    messages: generateSampleEmails(email.split('@')[0], email),
  });
}
