const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'src/utils/userAccess.ts'), 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const sandbox = { exports: {} };
vm.runInNewContext(code, sandbox);
const { resolveUserAccess, toggleUserAccess } = sandbox.exports;
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'src/data/menu-registry.json'), 'utf8'));
const menu = 'logs';
const permission = 'logs:view';
const role = { key: 'user', label: 'Member', menuKeys: ['dashboard', 'email'], permissions: ['dashboard:view', 'email:view'] };
let user = { email: 'member@example.com', username: 'Member', role: 'user', extraMenus: [], extraPermissions: [], removedMenus: [], removedPermissions: [], roleMenus: [], rolePermissions: [] };
const fixtures = [];
function check(label, menuOn, permissionOn, actionOn = false) {
  const actual = resolveUserAccess(user, role, catalog);
  assert.equal(actual.menuKeys.has(menu), menuOn, label + ' menu');
  assert.equal(actual.permissions.has(permission), permissionOn, label + ' permission');
  assert.equal(actual.permissions.has('register:run'), actionOn, label + ' action permission');
  fixtures.push({ label, role: structuredClone(role), user: structuredClone(user), menuOn, permissionOn, actionOn });
}
function click(field, value) { user = toggleUserAccess(user, role, catalog, field, value); }
check('new menu defaults to unassigned', false, false);
click('extraMenus', menu); check('grant personal menu without role grant', true, true);
click('extraMenus', menu); check('revoke personal menu and its view permission', false, false);
click('extraMenus', menu); check('restore personal menu clears both removal flags', true, true);
assert(!user.removedMenus.includes(menu)); assert(!user.removedPermissions.includes(permission));
click('extraPermissions', permission); check('revoke auto-added view permission', false, false);
click('extraMenus', menu); check('restore menu after revoking view permission', true, true);
click('extraPermissions', 'register:run'); check('add independent action permission', true, true, true);
click('extraPermissions', 'register:run'); check('revoke action permission', true, true);
click('extraPermissions', 'register:run'); check('restore action permission clears removal', true, true, true);
click('extraPermissions', 'register:run');
role.menuKeys.push(menu); role.permissions.push(permission);
check('role grant preserves existing personal grant', true, true);
click('extraMenus', menu); check('revoke overlapping personal and role menu', false, false);
click('extraMenus', menu); check('restore inherited menu clears denial', true, true);
assert(!user.extraMenus.includes(menu), 'restore inherited menu must not add personal grant');
role.menuKeys = role.menuKeys.filter(key => key !== menu); role.permissions = role.permissions.filter(code => code !== permission);
check('removing role menu removes inherited access', false, false);
click('extraMenus', menu); check('explicitly grant personal menu again', true, true);
role.menuKeys.push(menu); role.permissions.push(permission);
role.menuKeys = role.menuKeys.filter(key => key !== menu); role.permissions = role.permissions.filter(code => code !== permission);
check('removing role menu preserves independent personal grant', true, true);
user.removedMenus = [menu]; user.removedPermissions = [permission];
check('legacy contradictory data is displayed denied', false, false);
click('extraMenus', menu); check('explicit grant repairs legacy contradictory data', true, true);
click('extraPermissions', permission); check('view revocation hides menu', false, false);
click('extraPermissions', permission); check('permission-only grant does not recreate menu', false, true);
click('extraMenus', menu); check('menu grant after restoring permission', true, true);
if (process.argv.includes('--fixtures')) process.stdout.write(JSON.stringify(fixtures));
else console.log(`PASS: ${fixtures.length} user permission scenarios`);
